package io.screentrace.scanner;

import static org.junit.jupiter.api.Assertions.*;
import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;

/** Generated API docs are not application pages; they are skipped once, with a single counted diagnostic. */
class JavadocSkipTest {
  @Test void generatedJavadocIsSkippedAndCounted() throws Exception {
    Path root = Files.createTempDirectory("st-javadoc");
    Files.createDirectories(root.resolve("docs/org/example"));
    Files.createDirectories(root.resolve("web"));
    String page = "<!DOCTYPE HTML PUBLIC \"-//W3C//DTD HTML 4.01 Transitional//EN\">\n<!--NewPage-->\n<HTML>\n<HEAD>\n<!-- Generated by javadoc on Wed Oct 09 11:05:26 CEST 2013-->\n<TITLE>Thing</TITLE></HEAD><BODY><A HREF=\"../../index.html\">Overview</A></BODY></HTML>";
    Files.writeString(root.resolve("docs/index.html"), page);
    Files.writeString(root.resolve("docs/org/example/Thing.html"), page);
    Files.writeString(root.resolve("docs/org/example/package-summary.html"), "<html><head><!-- Generated by javadoc (17) --></head><body/></html>");
    Files.writeString(root.resolve("docs/overview.html"), "<html><body><a href=\"index.html\">API</a></body></html>");
    Files.writeString(root.resolve("web/index.html"), "<html><body><a href=\"login.do\">Login</a></body></html>");

    var inventory = new ProjectScanner().scan(root);
    var files = inventory.files().stream().map(path -> inventory.root().relativize(path).toString().replace('\\', '/')).sorted().toList();

    assertEquals(java.util.List.of("docs/overview.html", "web/index.html"), files);
    assertEquals(java.util.List.of("Generated Javadoc HTML skipped: 3 files"), inventory.diagnostics());
  }
}
